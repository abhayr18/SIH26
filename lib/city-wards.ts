/**
 * Retrieves the spatial ward map profile for any city with case-insensitive matching.
 */
export function getCitySpatialProfile(cityName: string, baseTemp: number = 40, baseHumidity: number = 45): CitySpatialProfile {
  if (!cityName) {
    return CITY_SPATIAL_PROFILES['Delhi'];
  }

  const cleanName = cityName.trim().toLowerCase();
  for (const [key, profile] of Object.entries(CITY_SPATIAL_PROFILES)) {
    if (key.toLowerCase() === cleanName) {
      return profile;
    }
  }

  // Partial match check (e.g. "Delhi NCR" -> "Delhi", "Pune PMC" -> "Pune")
  for (const [key, profile] of Object.entries(CITY_SPATIAL_PROFILES)) {
    if (cleanName.includes(key.toLowerCase()) || key.toLowerCase().includes(cleanName)) {
      return profile;
    }
  }

  return generateGenericCityWards(cityName, baseTemp, baseHumidity);
}
