/**
 * Retrieves the authentic spatial ward map profile for any monitored city.
 * Always resolves to authentic municipal corporation datasets with zero generic fallbacks.
 */
export function getCitySpatialProfile(cityName: string, _baseTemp: number = 40, _baseHumidity: number = 45): CitySpatialProfile {
  if (!cityName) {
    return CITY_SPATIAL_PROFILES['Delhi'];
  }

  const cleanName = cityName.trim().toLowerCase();
  for (const [key, profile] of Object.entries(CITY_SPATIAL_PROFILES)) {
    if (key.toLowerCase() === cleanName) {
      return profile;
    }
  }

  // Partial match check (e.g. "Delhi NCR" -> "Delhi", "Pune PMC" -> "Pune", "Mumbai BMC" -> "Mumbai")
  for (const [key, profile] of Object.entries(CITY_SPATIAL_PROFILES)) {
    if (cleanName.includes(key.toLowerCase()) || key.toLowerCase().includes(cleanName)) {
      return profile;
    }
  }

  // Default to Delhi profile if an unmonitored name is supplied
  return CITY_SPATIAL_PROFILES['Delhi'];
}
